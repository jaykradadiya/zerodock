/**
 * Returns a random adjective-noun slug (e.g., "cosmic-falcon")
 */
export function generateMemorableSlug(): string {
  const adj = ADJECTIVES[Math.floor(Math.random() * ADJECTIVES.length)];
  const noun = NOUNS[Math.floor(Math.random() * NOUNS.length)];
  return `${adj}-${noun}`;
}

/**
 * Generates a guaranteed unique tab/file name with extension (e.g., "cosmic-falcon.json").
 * Checks against existing names to ensure zero collisions.
 *
 * @param existingNames - Array of tab/file names currently in use
 * @param extension - File extension to append (defaults to '.json')
 */
export function generateUniqueTabName(
  existingNames: string[] = [],
  extension: string = '.json'
): string {
  const existingSet = new Set(existingNames.map((n) => n.toLowerCase().trim()));
  const ext = extension ? (extension.startsWith('.') ? extension : `.${extension}`) : '';

  const maxAttempts = 100;
  for (let i = 0; i < maxAttempts; i++) {
    const candidate = `${generateMemorableSlug()}${ext}`;
    if (!existingSet.has(candidate.toLowerCase())) {
      return candidate;
    }
  }

  // Fallback if all attempts collide (extremely rare with 3,400+ combinations)
  let counter = 2;
  const baseSlug = generateMemorableSlug();
  while (existingSet.has(`${baseSlug}-${counter}${ext}`.toLowerCase())) {
    counter++;
  }
  return `${baseSlug}-${counter}${ext}`;
}
